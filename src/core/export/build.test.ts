import { describe, expect, it } from 'vitest'
import { buildExport } from './build'
import type { BuildInput } from './build'
import { parseTemplate } from './template'
import { parseDiagnostics } from './diagnostics'
import { CITATION_STYLES, typstStyleFor } from './styles'

const TEMPLATE = `
[template]
id = "monographie"
name = { de = "Monographie", en = "Thesis" }

[[options]]
id = "author"
type = "text"
default = ""
label = { de = "Autor", en = "Author" }

[[options]]
id = "paper"
type = "enum"
default = "a4"
label = { de = "Papier", en = "Paper" }
values = ["a4", "us-letter"]

[[options]]
id = "title_page"
type = "bool"
default = true
label = { de = "Titelseite", en = "Title page" }
`
const parsed = parseTemplate(TEMPLATE)
if (!parsed.ok) throw new Error(parsed.message)
const INFO = parsed.value

function input(overrides: Partial<BuildInput> = {}): BuildInput {
  return {
    title: 'Meine "Arbeit"',
    language: 'de',
    sheets: [
      {
        path: 'einleitung/einleitung.typ',
        text: '= Einleitung <sec-einleitung>\n\nText ::mark::.\n',
      },
      {
        path: 'methoden/design.typ',
        text: '== Design <sec-design>\n\nSiehe @sec-einleitung und @sec-fehlt.\n',
      },
    ],
    profile: {
      name: 'Abgabe',
      template: 'monographie',
      citationStyle: 'apa-7',
      marks: 'hide',
      comments: 'remove',
      options: { author: 'A. Autor', paper: 'us-letter' },
    },
    template: {
      info: INFO,
      files: [
        { path: 'lib.typ', content: '// lib' },
        { path: 'style.toml', content: 'engine = 1' },
      ],
    },
    prelude: '// prelude',
    bibliography: '/library.bib',
    blockQuoteMarks: false,
    ...overrides,
  }
}
const file = (output: ReturnType<typeof buildExport>, path: string): string =>
  output.files.find((f) => f.path === path)?.content ?? ''

describe('buildExport', () => {
  it('writes the main file with the template, the options, the sheets in order, and the bibliography', () => {
    const output = buildExport(input())
    expect(output.main).toBe('_build/main.typ')
    expect(file(output, '_build/main.typ')).toBe(
      [
        '// Generated by the app on every export. Do not edit.',
        '// Project: Meine "Arbeit"',
        '#import "prelude.typ": *',
        '#import "template/lib.typ": project',
        '#show: project.with((title: "Meine \\"Arbeit\\"", lang: "de", author: "A. Autor", paper: "us-letter", title_page: true))',
        '',
        '#include "content/einleitung/einleitung.typ"',
        '#parbreak()',
        '#include "content/methoden/design.typ"',
        '',
        '#bibliography("/library.bib", title: "Literaturverzeichnis", style: "apa")',
        '',
      ].join('\n'),
    )
  })

  it('copies the template and the prelude into the build folder', () => {
    const output = buildExport(input())
    expect(file(output, '_build/template/lib.typ')).toBe('// lib')
    expect(file(output, '_build/template/style.toml')).toBe('engine = 1')
    expect(file(output, '_build/template/style.typ')).toContain('body: (font: "Libertinus Serif"')
    expect(file(output, '_build/prelude.typ')).toBe('// prelude')
  })

  it('writes each sheet preprocessed, and works out the links to headings across the sheets', () => {
    const output = buildExport(input())
    expect(file(output, '_build/content/einleitung/einleitung.typ')).toBe(
      '= Einleitung <sec-einleitung>\n\nText mark.\n',
    )
    expect(file(output, '_build/content/methoden/design.typ')).toBe(
      '== Design <sec-design>\n\nSiehe #link(<sec-einleitung>)[Abschnitt 1] und @sec-fehlt.\n',
    )
  })

  it('reports a reference to a heading that is not in the export, in its sheet and line', () => {
    expect(buildExport(input()).problems).toEqual([
      { sheet: 'methoden/design.typ', line: 3, message: { kind: 'reference', label: 'sec-fehlt' } },
    ])
  })

  /** The input with a style that sets `heading` values, as a template's style.toml would. */
  const styled = (style: string) =>
    input({
      template: { info: INFO, files: [{ path: 'style.toml', content: style }] },
    })

  it('links to the title where the template does not number headings', () => {
    const output = buildExport(styled('[element.heading]\nnumber_depth = "0"'))
    expect(file(output, '_build/content/methoden/design.typ')).toContain(
      '#link(<sec-einleitung>)[„Einleitung“]',
    )
  })

  it('writes the numbers of a reference the way the template numbers: roman chapters, letters below', () => {
    const output = buildExport(
      styled(
        '[element.heading_1]\nnumber_format = "roman"\n[element.heading_2]\nnumber_format = "alpha"\n',
      ),
    )
    expect(file(output, '_build/template/style.typ')).toContain('pattern: "I.A.1.1.1.1"')
    expect(file(output, '_build/content/methoden/design.typ')).toContain(
      '#link(<sec-einleitung>)[Abschnitt I]',
    )
  })

  it('names a heading deeper than the numbering by its title, and one above it by its number', () => {
    const output = buildExport(styled('[element.heading]\nnumber_depth = "1"'))
    expect(file(output, '_build/template/style.typ')).toContain('depth: 1')
    expect(file(output, '_build/content/methoden/design.typ')).toContain(
      '#link(<sec-einleitung>)[Abschnitt 1]',
    )
  })

  it('calls a section by the word the template sets', () => {
    const output = buildExport(styled('[element.references]\nsupplement_section = "Kap."'))
    expect(file(output, '_build/content/methoden/design.typ')).toContain(
      '#link(<sec-einleitung>)[Kap. 1]',
    )
    expect(file(output, '_build/template/style.typ')).toContain('supplement_section: "Kap."')
  })

  it('writes the title of the bibliography the template sets', () => {
    const plain = buildExport({ ...input(), bibliography: '/library.bib' })
    expect(file(plain, '_build/main.typ')).toContain('title: "Literaturverzeichnis"')
    const own = buildExport({
      ...styled('[element.bibliography]\ntitle_text = "Quellen"'),
      bibliography: '/library.bib',
    })
    expect(file(own, '_build/main.typ')).toContain('title: "Quellen"')
  })

  it('uses the defaults of the template for options the profile does not set, and drops unknown ones', () => {
    const output = buildExport(
      input({
        profile: { ...input().profile, options: { paper: 'nonsense', bogus: 'x', 'bad key': 'y' } },
      }),
    )
    expect(file(output, '_build/main.typ')).toContain(
      '(title: "Meine \\"Arbeit\\"", lang: "de", author: "", paper: "a4", title_page: true)',
    )
  })

  it('asks for quotation marks around block quotes, and leaves the bibliography out when there is none', () => {
    const main = file(
      buildExport(input({ blockQuoteMarks: true, bibliography: null })),
      '_build/main.typ',
    )
    expect(main).toContain('#set quote(quotes: true)')
    expect(main).not.toContain('#bibliography')
  })

  it('sets the chosen quotation marks for every quote, and nothing for the language default', () => {
    const main = (quoteStyle: 'auto' | 'de-guillemets') =>
      file(buildExport(input({ quoteStyle })), '_build/main.typ')
    expect(main('auto')).not.toContain('smartquote')
    expect(main('de-guillemets')).toContain(
      '#set smartquote(quotes: (double: ("»", "«"), single: ("›", "‹")))',
    )
  })

  it('cannot be broken out of by a title or an author with line breaks and quotes', () => {
    const output = buildExport(
      input({
        title: 'A\n#panic("x")',
        profile: { ...input().profile, options: { author: 'B"\n#panic()' } },
      }),
    )
    const main = file(output, '_build/main.typ')
    expect(main.split('\n').filter((l) => l.startsWith('#panic'))).toEqual([])
    expect(main).toContain('author: "B\\" #panic()"')
  })

  it('counts what is open in the sheets', () => {
    const output = buildExport(
      input({
        sheets: [
          {
            path: 'a.typ',
            text: 'Ein ::A:: und /* Notiz */ und @x/*#check*/ und y/*#cite-needed*/\n',
          },
        ],
      }),
    )
    expect(output.counts).toEqual({ highlights: 1, comments: 1, missingCitations: 1, checks: 1 })
  })
})

describe('parseDiagnostics', () => {
  it('reads the compiler’s short format and maps a line back to its sheet', () => {
    const found = parseDiagnostics(
      [
        '_build/content/methoden/design.typ:3:7: error: label `<sec-fehlt>` does not exist in the document',
        '_build/template/lib.typ:45:8: error: expected function, found dictionary',
        'something else',
        '_build/main.typ:5:0: warning: unknown font family',
      ].join('\n'),
    )
    expect(found).toEqual([
      expect.objectContaining({
        severity: 'error',
        sheet: 'methoden/design.typ',
        line: 3,
        column: 7,
      }),
      expect.objectContaining({ severity: 'error', sheet: null, file: '_build/template/lib.typ' }),
      expect.objectContaining({ severity: 'warning', sheet: null, line: 5 }),
    ])
  })
})

describe('citation styles', () => {
  it('map an id to the style Typst knows, and an unknown id to APA', () => {
    expect(typstStyleFor('harvard')).toBe('harvard-cite-them-right')
    expect(typstStyleFor('unbekannt')).toBe('apa')
    expect(new Set(CITATION_STYLES.map((s) => s.id)).size).toBe(CITATION_STYLES.length)
  })
})

describe('parseTemplate', () => {
  it('reads the options, and rejects a file without an id', () => {
    expect(INFO.options.map((o) => o.id)).toEqual(['author', 'paper', 'title_page'])
    expect(parseTemplate('[template]\nname = "x"').ok).toBe(false)
    expect(parseTemplate('not toml [').ok).toBe(false)
  })
})
