// Writes THIRD-PARTY-NOTICES.txt: the licenses of everything Ezetta ships that is not its own code.
//
//   1. The programs and data the package carries besides the app (Typst, LanguageTool, the Java
//      runtime, the thesaurus files, Marginalia, Electron), described below by hand.
//   2. The libraries and fonts bundled into the app's code (out/), found by reading the source:
//      a package counts when the app's code imports it, with everything it depends on. Each
//      one's license text comes from its own folder in node_modules.
//
// The file is committed so that it can be read in a checkout and is shown by the About tab in
// development; the package ships it as well. `node scripts/notices.mjs` writes it, and
// `--check` (run by `npm run check`) fails when it is out of date, for example after a dependency
// was added or updated.
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const OUTPUT = join(root, 'THIRD-PARTY-NOTICES.txt')
const read = (path) => readFileSync(join(root, path), 'utf8')

/** Declared packages that are build tools, shipped separately, or covered by hand below. */
const NOT_BUNDLED = new Set(['electron'])
/** Where the app's own code lives; tests and the component gallery are not part of the package. */
const SOURCE = 'src'
const SKIPPED = /(\.test\.ts|\.spec\.ts|\/testing\/|\/gallery\/|gallery\.html|\.d\.ts)$/

function* sourceFiles(dir) {
  for (const entry of readdirSync(join(root, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`
    if (entry.isDirectory()) yield* sourceFiles(path)
    else if (/\.(ts|svelte|css|html)$/.test(entry.name) && !SKIPPED.test(path)) yield path
  }
}

const manifest = JSON.parse(read('package.json'))
const declared = Object.keys({ ...manifest.dependencies, ...manifest.devDependencies })
const code = [...sourceFiles(SOURCE)].map(read).join('\n')

/** Whether the app's code names the package in an import, a CSS import or a dynamic import. */
const imported = (name) => {
  const escaped = name.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
  return new RegExp(`['"]${escaped}(['"/])`).test(code)
}

const packageDir = (name) => join(root, 'node_modules', name)
const packageJson = (name) =>
  JSON.parse(readFileSync(join(packageDir(name), 'package.json'), 'utf8'))

/** The packages the code imports, and everything they need to run. */
function bundled() {
  const found = new Set()
  const visit = (name) => {
    if (found.has(name) || !existsSync(packageDir(name))) return
    found.add(name)
    const info = packageJson(name)
    for (const dependency of Object.keys({
      ...info.dependencies,
      ...info.optionalDependencies,
    })) {
      visit(dependency)
    }
  }
  for (const name of declared) if (!NOT_BUNDLED.has(name) && imported(name)) visit(name)
  return [...found].sort()
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i

function licenseOf(name) {
  const info = packageJson(name)
  const spdx =
    typeof info.license === 'string' ? info.license : (info.license?.type ?? 'see the package')
  const texts = readdirSync(packageDir(name))
    .filter((file) => LICENSE_FILE.test(file))
    .sort()
    .map((file) =>
      readFileSync(join(packageDir(name), file), 'utf8')
        .replace(/\r\n/g, '\n')
        .trim(),
    )
  const author = typeof info.author === 'string' ? info.author : (info.author?.name ?? '')
  return { name, version: info.version, spdx, author, texts }
}

const RULE = '='.repeat(78)
const THIN = '-'.repeat(78)

function section(title) {
  return `${RULE}\n${title}\n${RULE}\n`
}

