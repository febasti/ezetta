function libraries() {
  const entries = bundled().map(licenseOf)
  // Packages whose license text is the same word for word are listed together.
  const groups = new Map()
  const noText = []
  for (const entry of entries) {
    if (entry.texts.length === 0) {
      noText.push(entry)
      continue
    }
    const text = entry.texts.join(`\n\n${THIN}\n\n`)
    const key = createHash('sha256').update(text).digest('hex')
    if (!groups.has(key)) groups.set(key, { text, members: [] })
    groups.get(key).members.push(entry)
  }
  const label = (entry) => `${entry.name} ${entry.version} (${entry.spdx})`
  const blocks = [...groups.values()]
    .sort((a, b) => label(a.members[0]).localeCompare(label(b.members[0])))
    .map(({ text, members }) => `${members.map(label).join('\n')}\n\n${text}`)
  const withoutText = noText.length
    ? `\nPackages without a license file of their own (the license is named in their package.json):\n${noText
        .map(
          (entry) =>
            `  ${entry.name} ${entry.version} (${entry.spdx})${entry.author ? `, ${entry.author}` : ''}`,
        )
        .join('\n')}\n`
    : ''
  return (
    `${section('2. Libraries and fonts built into the app')}
The app's code is bundled from the packages below, with the packages they depend on. The fonts
(Libertinus Serif, Libertinus Sans, IBM Plex Mono, Inter) are under the SIL Open Font License 1.1.
Source code and further notices of each package are on https://www.npmjs.com/package/<name>.

` +
    blocks.join(`\n\n${THIN}\n\n`) +
    `\n${withoutText}`
  )
}

function build() {
  return [
    HEADER,
    PROGRAMS,
    libraries(),
    `${section('3. Apache License 2.0 (Typst)')}\n${read('licenses/Apache-2.0.txt').trim()}\n`,
  ].join('\n')
}

const text = build()
if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
  if (current !== text) {
    console.error(
      'THIRD-PARTY-NOTICES.txt is out of date. Run `npm run notices` and commit the result.',
    )
    process.exit(1)
  }
  console.log('THIRD-PARTY-NOTICES.txt is up to date.')
} else {
  writeFileSync(OUTPUT, text)
  console.log(`Wrote ${OUTPUT} (${bundled().length} packages).`)
}
